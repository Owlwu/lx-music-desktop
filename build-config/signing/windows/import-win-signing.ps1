<#
.SYNOPSIS
  Import the shared LX Music code-signing certificate on Windows.

.DESCRIPTION
  Validate a .p12/.pfx for Windows builds, copy it into build-config\signing,
  and write signing.env for build-pack.js. Certificate-store import and local
  root trust are optional. Reuse the same Windows signing identity on each
  build machine to keep a consistent publisher across versions.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File import-win-signing.ps1 `
      -PfxPath .\lxmusic-codesign.p12 -Password 'secret' -ImportCert -TrustRoot

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File import-win-signing.ps1 `
      -PfxPath .\lxmusic-codesign.p12 -TrustRoot -Exe .\build\win-unpacked\lx-music-desktop.exe
#>
[CmdletBinding()]
param(
  [Parameter(Mandatory = $true, Position = 0)][string]$PfxPath,
  [string]$Password,
  [string]$PasswordFile,
  [string]$RepoRoot,
  [string]$SignIdentity,
  [switch]$ImportCert,
  [switch]$TrustRoot,
  [string]$Exe
)

$ErrorActionPreference = 'Stop'
$SigningDirName = 'lxmusic-codesign.p12'

function Fail([string]$Message) {
  Write-Host "[ERROR] $Message" -ForegroundColor Red
  exit 1
}

function Info([string]$Message) { Write-Host "[signing] $Message" -ForegroundColor Cyan }
function Note([string]$Message) { Write-Host "[signing] $Message" -ForegroundColor Yellow }

if (-not $RepoRoot) {
  $RepoRoot = (Resolve-Path -LiteralPath (Join-Path $PSScriptRoot '..\..\..')).Path
}
$SigningDir = Join-Path $RepoRoot 'build-config\signing'
$EnvFile = Join-Path $SigningDir 'signing.env'
$TargetP12 = Join-Path $SigningDir $SigningDirName

if (-not (Test-Path -LiteralPath $PfxPath)) { Fail "Certificate not found: $PfxPath" }
$PfxPath = (Resolve-Path -LiteralPath $PfxPath).Path

if (-not $Password -and $PasswordFile) {
  $Password = (Get-Content -Raw -LiteralPath $PasswordFile).Trim()
}
# Reuse the password already exported from the Mac (signing.env) when present
if (-not $Password -and (Test-Path -LiteralPath $EnvFile)) {
  foreach ($line in (Get-Content -LiteralPath $EnvFile)) {
    if ($line -match '^CSC_KEY_PASSWORD=(.*)$') { $Password = $Matches[1].Trim().Trim('"').Trim("'") }
  }
}
if (-not $Password) {
  $secure = Read-Host 'Certificate password' -AsSecureString
  $bstr = [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure)
  try { $Password = [Runtime.InteropServices.Marshal]::PtrToStringUni($bstr) }
  finally { [Runtime.InteropServices.Marshal]::ZeroFreeBSTR($bstr) }
}
if (-not $Password) { Fail 'A certificate password is required.' }

# --- validate the certificate without importing it -------------------------
$cert = $null
try {
  $cert = [System.Security.Cryptography.X509Certificates.X509Certificate2]::new(
    $PfxPath,
    $Password,
    [System.Security.Cryptography.X509Certificates.X509KeyStorageFlags]::EphemeralKeySet
  )
}
catch {
  Fail "Cannot open the .p12/.pfx (wrong password or unsupported format): $($_.Exception.Message)"
}
if (-not $cert.HasPrivateKey) {
  Fail 'The certificate has no private key. Export it again together with its private key.'
}

$ekuExt = $cert.Extensions | Where-Object { $_.Oid.Value -eq '2.5.29.37' } | Select-Object -First 1
if ($ekuExt) {
  $hasCodeSigning = $false
  foreach ($oid in $ekuExt.EnhancedKeyUsages) {
    if ($oid.Value -eq '1.3.6.1.5.5.7.3.3' -or $oid.FriendlyName -eq 'Code Signing') { $hasCodeSigning = $true }
  }
  if (-not $hasCodeSigning) {
    Fail 'Extended Key Usage does not contain "Code Signing" (1.3.6.1.5.5.7.3.3).'
  }
}
else {
  Note 'Certificate has no Extended Key Usage extension; signing may fail.'
}

if ($TrustRoot -and $cert.Subject -ne $cert.Issuer) {
  Fail 'TrustRoot requires a self-signed development certificate.'
}

$subjectCn = (($cert.Subject -split ',\s*') | Where-Object { $_ -match '^CN=' } | Select-Object -First 1)
if ($subjectCn) { $subjectCn = $subjectCn -replace '^CN=', '' } else { $subjectCn = $cert.Subject }
if (-not $SignIdentity) { $SignIdentity = $subjectCn }

# --- keep the .p12 inside the repo so build-pack.js can find it ------------
if (-not (Test-Path -LiteralPath $SigningDir)) {
  New-Item -ItemType Directory -Path $SigningDir | Out-Null
}
if ($PfxPath -ne $TargetP12) {
  Copy-Item -LiteralPath $PfxPath -Destination $TargetP12 -Force
  Info "Copied certificate to build-config\signing\$SigningDirName"
}

# --- merge with an existing signing.env so the mac part is preserved ------
$existing = @{}
if (Test-Path -LiteralPath $EnvFile) {
  foreach ($line in (Get-Content -LiteralPath $EnvFile)) {
    if ($line -match '^\s*([A-Za-z0-9_]+)\s*=\s*(.*?)\s*$') {
      $existing[$Matches[1]] = $Matches[2]
    }
  }
}

$identity = $existing['MAC_SIGN_IDENTITY']
if (-not $identity) { $identity = $SignIdentity }
$notarize = $existing['MAC_NOTARIZE']
if (-not $notarize) { $notarize = '0' }

$lines = @(
  '# Auto-generated by import-win-signing.ps1 (contains the certificate password, do NOT commit)',
  'CSC_LINK=./build-config/signing/lxmusic-codesign.p12',
  "CSC_KEY_PASSWORD=$Password",
  "MAC_SIGN_IDENTITY=$identity",
  "MAC_NOTARIZE=$notarize"
)
$utf8NoBom = New-Object System.Text.UTF8Encoding($false)
[IO.File]::WriteAllText($EnvFile, (($lines -join "`n") + "`n"), $utf8NoBom)
Info "Wrote build-config\signing\signing.env"

# --- optional: import into the current user store -------------------------
if ($ImportCert) {
  $securePwd = ConvertTo-SecureString -String $Password -AsPlainText -Force
  Import-PfxCertificate -FilePath $TargetP12 -CertStoreLocation 'Cert:\CurrentUser\My' -Password $securePwd | Out-Null
  Info "Imported into Cert:\CurrentUser\My (thumbprint $($cert.Thumbprint))"
}

# --- optional: trust a self-signed development certificate on this PC -----
if ($TrustRoot) {
  $isAdmin = ([Security.Principal.WindowsPrincipal][Security.Principal.WindowsIdentity]::GetCurrent()).IsInRole(
    [Security.Principal.WindowsBuiltInRole]::Administrator)
  if (-not $isAdmin) {
    Note 'TrustRoot needs an elevated PowerShell. Re-run as Administrator, or run this script without -TrustRoot.'
  }
  else {
    $cer = Join-Path $env:TEMP ("lxmusic-{0}.cer" -f $cert.Thumbprint)
    [IO.File]::WriteAllBytes($cer, $cert.Export([System.Security.Cryptography.X509Certificates.X509ContentType]::Cert))
    try {
      Import-Certificate -FilePath $cer -CertStoreLocation 'Cert:\LocalMachine\Root' | Out-Null
      Info 'Self-signed certificate added to LocalMachine\Root'
    }
    finally {
      Remove-Item -LiteralPath $cer -Force -ErrorAction SilentlyContinue
    }
  }
}

# --- optional: verify an existing artifact --------------------------------
if ($Exe) {
  if (-not (Test-Path -LiteralPath $Exe)) { Fail "File to verify not found: $Exe" }
  $sig = Get-AuthenticodeSignature -LiteralPath $Exe
  Write-Host ''
  Info "Authenticode: $($sig.Status)"
  if ($sig.SignerCertificate) {
    Info "Signer: $($sig.SignerCertificate.Subject)"
    Info "Thumbprint: $($sig.SignerCertificate.Thumbprint)"
    if ($sig.SignerCertificate.Thumbprint -ne $cert.Thumbprint) {
      Note 'The file is signed with a DIFFERENT certificate than the one just configured.'
    }
    else {
      Info 'The file is signed with the configured certificate.'
    }
  }
  else {
    Note 'The file is not signed.'
  }
}

Write-Host ''
Info "Publish name: $subjectCn"
Info "Thumbprint: $($cert.Thumbprint)"
Info "Valid until: $($cert.NotAfter.ToString('yyyy-MM-dd'))"
Write-Host ''
Info 'Next steps:'
Write-Host '  npm run pack:win:setup:x64          # builds + signs the NSIS installer'
Write-Host '  Get-AuthenticodeSignature .\build\win-unpacked\lx-music-desktop.exe'
Write-Host ''
